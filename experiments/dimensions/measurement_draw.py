import cv2


# ============================================================
# VẼ KẾT QUẢ ĐO LÊN ẢNH GỐC
# ============================================================

def draw_global_measurement(
    image,
    roi_box,
    horizontal_result=None,
    vertical_result=None
):

    result = image.copy()

    # --------------------------------------------------------
    # Không có ROI
    # --------------------------------------------------------

    if roi_box is None:
        return result


    rx1, ry1, rx2, ry2 = roi_box


    # ========================================================
    # VẼ ROI MỞ RỘNG
    # ========================================================

    cv2.rectangle(
        result,
        (rx1, ry1),
        (rx2, ry2),
        (0, 165, 255),
        2
    )


    # ========================================================
    # ĐƯỜNG NGANG GIỮA ROI
    #
    # NGANG
    # ========================================================

    if horizontal_result is not None:

        center_y = (
            ry1
            + horizontal_result["center"]
        )

        x1 = (
            rx1
            + horizontal_result["start"]
        )

        x2 = (
            rx1
            + horizontal_result["end"]
        )


        # ----------------------------------------------------
        # Đường đo
        # ----------------------------------------------------

        cv2.line(
            result,
            (x1, center_y),
            (x2, center_y),
            (0, 255, 0),
            3
        )


        # ----------------------------------------------------
        # Điểm đầu
        # ----------------------------------------------------

        cv2.circle(
            result,
            (x1, center_y),
            6,
            (0, 0, 255),
            -1
        )


        # ----------------------------------------------------
        # Điểm cuối
        # ----------------------------------------------------

        cv2.circle(
            result,
            (x2, center_y),
            6,
            (255, 0, 0),
            -1
        )


    # ========================================================
    # ĐƯỜNG DỌC GIỮA ROI
    #
    # DỌC
    # ========================================================

    if vertical_result is not None:

        center_x = (
            rx1
            + vertical_result["center"]
        )

        y1 = (
            ry1
            + vertical_result["start"]
        )

        y2 = (
            ry1
            + vertical_result["end"]
        )


        # ----------------------------------------------------
        # Đường đo
        # ----------------------------------------------------

        cv2.line(
            result,
            (center_x, y1),
            (center_x, y2),
            (255, 0, 0),
            3
        )


        # ----------------------------------------------------
        # Điểm đầu
        # ----------------------------------------------------

        cv2.circle(
            result,
            (center_x, y1),
            6,
            (0, 0, 255),
            -1
        )


        # ----------------------------------------------------
        # Điểm cuối
        # ----------------------------------------------------

        cv2.circle(
            result,
            (center_x, y2),
            6,
            (255, 0, 0),
            -1
        )


    return result


# ============================================================
# HIỂN THỊ TEXT KẾT QUẢ
# ============================================================

def put_results(
    image,
    lines
):

    result = image.copy()

    y = 35


    for text in lines:

        cv2.putText(
            result,
            text,
            (20, y),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.7,
            (0, 255, 255),
            2,
            cv2.LINE_AA
        )

        y += 30


    return result